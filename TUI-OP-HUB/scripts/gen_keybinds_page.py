#!/usr/bin/env python3
"""Render `tui-op-hub --export-keybinds` JSON to a static HTML page.

CI tool (D195): the docs.yml workflow runs the TUI binary headlessly with
`--export-keybinds`, pipes the JSON here, and deploys keybinds.html to
GitHub Pages. Pure stdlib — no network access at render time.

Usage: gen_keybinds_page.py < keybinds.json > keybinds.html
"""
import html
import json
import sys

TITLES = {
    "dashboard": "Dashboard",
    "knowledge": "Knowledge (commands / apps / scripts)",
    "projects": "Projects",
    "workflows": "Workflows",
    "secrets": "Secrets",
    "configs": "Configs",
    "plugins": "Plugins",
    "packages": "Packages",
    "settings": "Settings",
}

CSS = """\
:root { color-scheme: dark; }
body { margin: 0; padding: 2.5rem 1.5rem 4rem; background: #0e1415;
       color: #dee3e5; font: 15px/1.55 system-ui, sans-serif; }
main { max-width: 52rem; margin: 0 auto; }
h1 { font-size: 1.7rem; } p.muted { color: #6a7075; }
h2 { font-size: 1.15rem; color: #82d3e0; margin: 2.2rem 0 .6rem;
     padding-bottom: .3rem; border-bottom: 1px solid #262d2e; }
table { width: 100%; border-collapse: collapse; }
td { padding: .35rem .5rem; border-bottom: 1px solid #1a2022; vertical-align: top; }
td:first-child { white-space: nowrap; width: 7rem; }
kbd { font: 600 .85rem ui-monospace, monospace; color: #82d3e0;
      background: #16323a; border: 1px solid #2b444c; border-radius: 4px;
      padding: .1rem .4rem; }
"""


def table(pairs):
    rows = "".join(
        f"<tr><td><kbd>{html.escape(k)}</kbd></td><td>{html.escape(label)}</td></tr>"
        for k, label in pairs
    )
    return f"<table>{rows}</table>"


def main():
    data = json.load(sys.stdin)
    sections = ["<section><h2>Global</h2>", table(data["global"]), "</section>"]
    for name, pairs in data["screens"].items():
        title = html.escape(TITLES.get(name, name.capitalize()))
        sections += [f'<section id="{html.escape(name)}"><h2>{title}</h2>', table(pairs), "</section>"]
    body = html.escape("tui-op-hub — keybinds (generated by docs.yml from "
                       "cargo run -- --export-keybinds; do not edit by hand)")
    page = (
        "<!doctype html><html lang=en><head><meta charset=utf-8>"
        "<meta name=viewport content='width=device-width,initial-scale=1'>"
        "<title>tui-op-hub keybinds</title>"
        f"<style>{CSS}</style></head><body><main>"
        "<h1>\u2328\ufe0f keybinds — TUI-OP-HUB</h1>"
        f"<p class=muted>{body}</p>"
        "".join(sections) +
        "</main></body></html>\n"
    )
    sys.stdout.write(page)


if __name__ == "__main__":
    main()
